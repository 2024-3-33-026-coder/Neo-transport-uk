--              storage of authenticated Spoke Dispatch webhook events.

CREATE TABLE IF NOT EXISTS public.spoke_webhook_events (
  event_hash text PRIMARY KEY,
  event_type text NOT NULL,
  event_version text NOT NULL,
  event_created_at timestamptz NOT NULL,
  received_at timestamptz NOT NULL DEFAULT now(),
  payload jsonb NOT NULL,
  processing_status text NOT NULL DEFAULT 'received',
  processed_at timestamptz NULL,
  processing_error text NULL,
  CONSTRAINT check_spoke_webhook_processing_status
    CHECK (processing_status IN ('received', 'processed', 'failed', 'ignored')),
  CONSTRAINT check_spoke_webhook_event_hash_format
    CHECK (length(event_hash) = 64)
);

-- Indexes for efficient querying by type, timestamp, and inbox processing status
CREATE INDEX IF NOT EXISTS idx_spoke_webhook_events_type
  ON public.spoke_webhook_events (event_type);

CREATE INDEX IF NOT EXISTS idx_spoke_webhook_events_created_at
  ON public.spoke_webhook_events (event_created_at DESC);

CREATE INDEX IF NOT EXISTS idx_spoke_webhook_events_status
  ON public.spoke_webhook_events (processing_status);

-- Enable Row Level Security (RLS)
ALTER TABLE public.spoke_webhook_events ENABLE ROW LEVEL SECURITY;

-- Explicitly revoke all table privileges from PUBLIC, anon, and authenticated roles.
-- This table is strictly an internal inbox for the server-side service_role.
