REVOKE ALL ON TABLE public.spoke_webhook_events FROM PUBLIC, anon, authenticated;

-- Grant required DML privileges strictly to service_role
GRANT SELECT, INSERT, UPDATE ON TABLE public.spoke_webhook_events TO service_role;

